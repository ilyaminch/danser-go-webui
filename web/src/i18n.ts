export function t(
  value: string,
  params: Record<string, string | number> = {},
): string {
  const message = language === "en" ? (english[value] ?? value) : value;
  return message.replace(/\{(\w+)\}/g, (match, key) =>
    String(params[key] ?? match),
  );
}
